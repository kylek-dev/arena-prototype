#!/usr/bin/env node
// Generates the palette bindings from docs/palette.json, the single source of
// truth for every color the game shows (see docs/ART-DIRECTION.md).
//
//   node scripts/palette.mjs          write the bindings
//   node scripts/palette.mjs --check  fail if any binding is out of date
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

export const root = join(dirname(fileURLToPath(import.meta.url)), "..");
export const source = "docs/palette.json";
export const targets = {
  css: "web/src/styles/palette.css",
  ts: "web/src/domain/palette.ts",
  rust: "crates/arena-palette/src/swatches.rs",
};
const banner = `Generated by scripts/palette.mjs from ${source}. Do not edit.`;

export function load() {
  return JSON.parse(readFileSync(join(root, source), "utf8"));
}

export function swatches(spec) {
  return spec.families.flatMap((family) => family.swatches);
}

/** Throws on structural problems a reviewer could miss in a long JSON diff. */
export function validate(spec) {
  const ids = new Set();
  const hexes = new Map();
  for (const { id, hex, use } of swatches(spec)) {
    if (!/^[a-z]+(-[a-z0-9]+)+$/.test(id)) throw new Error(`bad swatch id ${id}`);
    if (ids.has(id)) throw new Error(`duplicate swatch id ${id}`);
    if (!/^#[0-9a-f]{6}$/.test(hex)) throw new Error(`${id}: hex must be #rrggbb lowercase`);
    if (hexes.has(hex)) throw new Error(`${id} repeats ${hexes.get(hex)} (${hex})`);
    if (!use) throw new Error(`${id}: describe where the swatch is used`);
    ids.add(id);
    hexes.set(hex, id);
  }
  const known = (id, where) => {
    if (!ids.has(id)) throw new Error(`${where} names unknown swatch ${id}`);
  };
  for (const [name, scale] of Object.entries(spec.radix.scales)) {
    if (scale.solid.length !== 12 || scale.alpha.length !== 12)
      throw new Error(`radix ${name} needs 12 solid and 12 alpha steps`);
    for (const id of scale.solid) known(id, `radix ${name}`);
    for (const [id, percent] of scale.alpha) {
      known(id, `radix ${name}`);
      if (!(percent >= 0 && percent <= 100)) throw new Error(`radix ${name}: bad alpha ${percent}`);
    }
    known(scale.contrast, `radix ${name}`);
  }
  known(spec.radix.overlays.black, "radix overlays");
  known(spec.radix.overlays.white, "radix overlays");
}

const pal = (id) => `var(--pal-${id})`;
const mix = (id, percent) =>
  percent === 100 ? pal(id) : `color-mix(in srgb, ${pal(id)} ${percent}%, transparent)`;

function css(spec) {
  const lines = [`/* ${banner} */`, ":root {"];
  for (const family of spec.families)
    for (const { id, hex } of family.swatches) lines.push(`  --pal-${id}: ${hex};`);
  lines.push("}", "");
  lines.push(
    "/* Radix Themes scales, redrawn from the palette. Doubled selectors outrank",
    "   Radix's own (including its display-p3 variants) regardless of order. */",
    ":root:root,",
    ".light.light,",
    ".light-theme.light-theme,",
    ".dark.dark,",
    ".dark-theme.dark-theme {",
  );
  for (const [name, scale] of Object.entries(spec.radix.scales)) {
    scale.solid.forEach((id, i) => lines.push(`  --${name}-${i + 1}: ${pal(id)};`));
    scale.alpha.forEach(([id, percent], i) =>
      lines.push(`  --${name}-a${i + 1}: ${mix(id, percent)};`),
    );
    lines.push(
      `  --${name}-contrast: ${pal(scale.contrast)};`,
      `  --${name}-surface: ${mix(scale.solid[1], 80)};`,
      `  --${name}-indicator: ${pal(scale.solid[8])};`,
      `  --${name}-track: ${pal(scale.solid[8])};`,
    );
  }
  const { black, white, percent } = spec.radix.overlays;
  percent.forEach((p, i) => lines.push(`  --black-a${i + 1}: ${mix(black, p)};`));
  percent.forEach((p, i) => lines.push(`  --white-a${i + 1}: ${mix(white, p)};`));
  lines.push("}", "");
  return lines.join("\n");
}

function ts(spec) {
  const lines = [`// ${banner}`, "export const palette = {"];
  for (const { id, hex } of swatches(spec)) lines.push(`  "${id}": "${hex}",`);
  lines.push("} as const;", "", "export type PaletteId = keyof typeof palette;", "");
  return lines.join("\n");
}

const constName = (id) => id.toUpperCase().replaceAll("-", "_");

function rust(spec) {
  const lines = [`// ${banner}`, "use crate::Swatch;", ""];
  for (const family of spec.families) {
    lines.push(`// ${family.name}: ${family.role}`);
    for (const { id, hex, use } of family.swatches) {
      lines.push(
        `/// ${use}.`,
        `pub const ${constName(id)}: Swatch = Swatch::new("${id}", 0x${hex.slice(1)});`,
      );
    }
    lines.push("");
  }
  lines.push("/// Every swatch, in palette order.", "pub const ALL: &[Swatch] = &[");
  for (const { id } of swatches(spec)) lines.push(`    ${constName(id)},`);
  lines.push("];", "");
  return lines.join("\n");
}

/** The generated text of every binding, keyed by repository path. */
export function outputs(spec = load()) {
  validate(spec);
  return { [targets.css]: css(spec), [targets.ts]: ts(spec), [targets.rust]: rust(spec) };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes("--check");
  let stale = 0;
  for (const [path, text] of Object.entries(outputs())) {
    const full = join(root, path);
    let current = null;
    try {
      current = readFileSync(full, "utf8");
    } catch {}
    if (current === text) continue;
    if (check) {
      console.error(`${path} is out of date; run node scripts/palette.mjs`);
      stale += 1;
    } else {
      writeFileSync(full, text);
      console.log(`wrote ${path}`);
    }
  }
  process.exit(stale ? 1 : 0);
}
